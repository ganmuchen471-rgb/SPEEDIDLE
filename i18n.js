// 获取翻译文本
function t(key) {
    const langData = I18N_DATA[currentLang];
    if (langData && langData[key] !== undefined) return langData[key];
    // 回退到英文
    const enData = I18N_DATA['en'];
    if (enData && enData[key] !== undefined) return enData[key];
    // 找不到则返回key本身
    return key;
}

// 获取当前语言
function getLanguage() {
    return currentLang;
}

// 设置语言（存储在 localStorage 中，独立于存档）
function setLanguage(lang) {
    if (!LANGUAGES.includes(lang)) return;
    currentLang = lang;
    try {
        localStorage.setItem('speedIdle_language', lang);
    } catch(e) { /* 忽略存储错误 */ }
    applyTranslations();
    // 触发UI刷新
    if (typeof render === 'function') render();
    if (typeof updateTranscendUI === 'function') updateTranscendUI();
    if (typeof updateQuantumUI === 'function') updateQuantumUI();
    if (typeof updateElementUI === 'function') updateElementUI();
    if (typeof updateAchievementUI === 'function') updateAchievementUI();
    if (typeof updateFlowUI === 'function') updateFlowUI();
    if (typeof updateMilestoneUI === 'function') updateMilestoneUI();
    if (typeof generateSaveSlots === 'function') generateSaveSlots();
    if (typeof updateSaveSlots === 'function') updateSaveSlots();
    if (typeof applySettingsToUI === 'function') applySettingsToUI();
    if (typeof updateCountdowns === 'function') updateCountdowns();
}

// 初始化语言（首次打开默认英文）
function initLanguage() {
    try {
        const saved = localStorage.getItem('speedIdle_language');
        if (saved && LANGUAGES.includes(saved)) {
            currentLang = saved;
        } else {
            currentLang = 'en'; // 默认英文
        }
    } catch(e) {
        currentLang = 'en';
    }
}

// 应用翻译到 HTML 中带有 data-i18n 属性的元素
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        if (text) el.textContent = text;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        const text = t(key);
        if (text) el.placeholder = text;
    });
}

// 页面加载时初始化语言
initLanguage();
